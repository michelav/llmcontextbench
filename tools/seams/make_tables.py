"""SEAMS 2027 LaTeX tables (booktabs) from the v3 baseline, replay reports, pilots and the S-E' live study.

Usage: python tools/seams/make_tables.py [--out docs/seams2027/tables]
No provider calls. Replay values are marked as estimated in the captions.
"""
import argparse, json
from pathlib import Path
from statistics import mean, median
from ctxbench.studies.study import _quantile
import se3_summary as se3

BASELINE = 'baselines/repoqa-long64-v3'
LIVE = 'studies/seams3-inline-degradation'
REPLAY = Path('studies/replay-v3calib')
CONFIG_LABELS = {'inline-code-full': 'inline (full code)', 'local-mcp-direct': 'MCP direct',
                 'local-mcp-lean': 'MCP lean', 'local-function-lean': 'function lean',
                 'local-function-default': 'function default', 'local-mcp-default': 'MCP default'}


def table(caption, label, columns, header, rows):
    body = '\n'.join(' & '.join(row) + r' \\' for row in rows)
    return (f'% generated by tools/seams/make_tables.py; do not edit\n'
            f'\\begin{{table}}[t]\n\\centering\\small\n\\caption{{{caption}}}\n\\label{{{label}}}\n'
            f'\\begin{{tabular}}{{{columns}}}\n\\toprule\n{" & ".join(header)} \\\\\n\\midrule\n{body}\n'
            f'\\bottomrule\n\\end{{tabular}}\n\\end{{table}}\n')


def catalogue():
    observations = json.load(open(f'{BASELINE}/frozen.json'))['payload']['observations']
    patterns = json.load(open(f'{BASELINE}/interaction-patterns.json'))[BASELINE]['configurations']
    rows = []
    for config in sorted(CONFIG_LABELS, key=lambda c: median(o['durationMs'] for o in observations if o['configuration'] == c)):
        obs = [o for o in observations if o['configuration'] == config]
        durations = [o['durationMs'] for o in obs]
        rows.append([CONFIG_LABELS[config], f'{median(durations)/1000:.1f}', f'{_quantile(durations, .9)/1000:.1f}',
                     f"{patterns[config]['meanModelCalls']:.1f}",
                     f"{mean(o['tokens']['value'] for o in obs)/1000:.1f}",
                     f"{sum(o['passed'] is True for o in obs)}/{len(obs)}"])
    return table('Configuration catalogue: v3 calibration (4 calibration targets, 144 requests per configuration). '
                 'Latency and tokens per request; tokens are provider-reported.', 'tab:catalogue', 'lrrrrr',
                 ['Configuration', 'Median (s)', 'p90 (s)', 'Model calls', 'Tokens (k)', 'Pass'], rows)


def live_results(prep, rows, summ):
    t = se3.arm_table(rows, summ)
    out = []
    for arm in se3.ARMS:
        a, b = t[(arm, 'stationary')], t[(arm, 'inline-degraded')]
        out.append([arm, f"{a['misses']:.1f}", f"{a['tokens']/1e3:.0f}",
                    '/'.join(f'{x:.1f}' for x in b['phaseMisses']), f"{b['misses']:.1f}", f"{b['tokens']/1e3:.0f}",
                    f"{100*b['directShare']:.0f}", f"{100*b['passRate']:.1f}"])
    return table('S-E\\textsuperscript{\\prime} live results: means per 96-request episode over 5 seeds (latency limit 7 s). '
                 'Degraded: inline +9 s on requests 31--60; misses per phase (1--30/31--60/61--96). '
                 'Tokens are answer tokens in thousands (lower bound).', 'tab:se-results', 'lrrrrrrr',
                 ['Arm', 'Stat. misses', 'Stat. tokens', 'Degr. misses by phase', 'Degr. misses', 'Degr. tokens',
                  'Direct (\\%)', 'Pass (\\%)'], out)


def live_contrasts(prep, rows):
    out = []
    for left, right in se3.CONTRASTS:
        m = se3.contrast(prep, rows, left, right, se3.miss)
        k = se3.contrast(prep, rows, left, right, se3.tokens)
        lo, hi = m['bootstrap95']; tlo, thi = k['bootstrap95']
        out.append([f'{left} -- {right}', f"{m['meanDifference']:+.2f} [{lo:+.2f}, {hi:+.2f}]",
                    f"{k['meanDifference']/1e3:+.1f} [{tlo/1e3:+.1f}, {thi/1e3:+.1f}]"])
    return table('S-E\\textsuperscript{\\prime} delay phase (requests 31--60): per-request paired differences with 95\\% '
                 'target-cluster bootstrap intervals (16 targets, stratified by language, 1{,}000 replicates). '
                 'Primary contrast: v2 -- frozen.', 'tab:se-contrasts', 'lrr',
                 ['Contrast', 'Miss probability', 'Tokens (k)'], out)


def validation():
    def replay(path, point=None):
        points = json.load(open(path))['points']
        p = next(p for p in points if point is None or p['name'] == point)
        return {k: v['deadlineMisses'] for k, v in p['policies'].items()}
    def pilot(path):
        return {s['policyName']: s['deadlineMisses'] for s in json.load(open(f'{path}/analysis.json'))['summaries']}
    _, rows, summ = se3.load(LIVE)
    t = se3.arm_table(rows, summ)
    cases = [('P2 (v2, MCP lean delayed)', replay('studies/replay-validation/p2.json'), pilot('studies/pilot-degradation'),
              {'fixed': 'cheap', 'v2': 'v2'}, '1 ep.'),
             ('P3 (v2, inline delayed, lean fallback)', replay('studies/replay-validation/p3.json'),
              pilot('studies/pilot-inline-degradation'), {'fixed': 'inline', 'v2': 'v2'}, '1 ep.'),
             ('P3\\textsuperscript{\\prime} (v3, direct fallback)', replay('studies/replay-validation/p3v3.json'),
              pilot('studies/pilot-v3-inline-degradation'), {'fixed': 'inline', 'v2': 'v2'}, '1 ep.'),
             ('S-E\\textsuperscript{\\prime} (v3, 96 requests)', replay(REPLAY / 'inline-degradation.json', 'L7000-d9000-n30'),
              {arm: t[(arm, 'inline-degraded')]['misses'] for arm in se3.ARMS}, {'fixed': 'inline', 'v2': 'v2'}, '5 ep.')]
    out = []
    for name, rp, live, keys, n in cases:
        rp = {**rp, 'v2': rp.get('v2', rp.get('v2-t10-ttl10'))}
        fmt = lambda v: str(v) if isinstance(v, int) else f'{v:.1f}'
        cells = [f'{rp[a]:.1f} / {fmt(live[a])}' for a in (keys['fixed'], 'frozen', 'v1', keys['v2'])]
        out.append([name, n] + cells)
    return table('Replay (estimated) against live deadline misses per episode. Pilots: 48 requests, one live episode per arm; '
                 'replay: 50 or 30 replicates per seed.', 'tab:validation', 'llrrrr',
                 ['Case', 'Live', 'Fixed', 'Frozen', 'v1', 'v2'], out)


def ablation():
    points = {p['name']: p for p in json.load(open(REPLAY / 'inline-degradation.json'))['points']}
    degraded, stationary = points['L7000-d9000-n30']['policies'], points['stationary-L7000']['policies']
    names = ['frozen', 'v1'] + sorted(n for n in degraded if n.startswith('v2')) + ['oracle']
    out = [[n.replace('_', '\\_') + (' (selected)' if n == 'v2-t10-ttl10' else ''),
            f"{degraded[n]['deadlineMisses']:.1f}", f"{degraded[n]['tokensLowerBound']/1e3:.0f}",
            f"{stationary[n]['deadlineMisses']:.1f}", f"{stationary[n]['tokensLowerBound']/1e3:.0f}"] for n in names]
    return table('Replay ablation (estimated) at the S-E\\textsuperscript{\\prime} point (limit 7 s, inline +9 s on requests 31--60) '
                 'and without a disturbance: misses and tokens (thousands) per episode.', 'tab:ablation', 'lrrrr',
                 ['Policy', 'Degr. misses', 'Degr. tokens', 'Stat. misses', 'Stat. tokens'], out)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--out', default='docs/seams2027/tables')
    args = parser.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    prep, rows, summ = se3.load(LIVE)
    for name, text in [('catalogue', catalogue()), ('se-results', live_results(prep, rows, summ)),
                       ('se-contrasts', live_contrasts(prep, rows)), ('validation', validation()),
                       ('ablation', ablation())]:
        (out / f'{name}.tex').write_text(text)
        print('wrote', name)


if __name__ == '__main__':
    main()
